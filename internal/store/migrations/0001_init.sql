CREATE TABLE flag_set_version
(
    environment TEXT        NOT NULL,
    version     BIGINT      NOT NULL,
    document    JSONB       NOT NULL,
    comment     TEXT,
    created_by  TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (environment, version),
    CONSTRAINT flag_set_version_positive CHECK (version > 0)
);

CREATE TABLE exposure
(
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment TEXT        NOT NULL,
    flag_key    TEXT        NOT NULL,
    variation   TEXT        NOT NULL,
    reason      TEXT        NOT NULL,
    rule_id     TEXT,
    user_key    TEXT        NOT NULL,
    version     BIGINT      NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX exposure_flag_time ON exposure (environment, flag_key, occurred_at DESC);
CREATE INDEX exposure_user ON exposure (environment, user_key);
